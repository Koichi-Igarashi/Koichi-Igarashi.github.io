# Refresh citation counts in data/citations.yml from Google Scholar.
#
#   Rscript scripts/update_citations.R
#
# Optional and run by hand (Google Scholar often blocks automated requests
# from cloud servers, so the website build itself never calls it). Needs the
# `scholar` package: install.packages("scholar").
# Papers are matched by title (or `scholar_title` in data/publications.yml).

scholar_id <- "AEWO65QAAAAJ"
publications_path <- "data/publications.yml"
citations_path <- "data/citations.yml"

if (!requireNamespace("scholar", quietly = TRUE)) {
  stop("Please install the 'scholar' package first: install.packages(\"scholar\")", call. = FALSE)
}

normalise_title <- function(x) {
  x <- tolower(gsub("*", "", x, fixed = TRUE))
  x <- gsub("[[:punct:]]", " ", x)
  trimws(gsub("\\s+", " ", x))
}

scholar_pubs <- scholar::get_publications(scholar_id)
scholar_keys <- normalise_title(scholar_pubs$title)

pubs <- yaml::read_yaml(publications_path)$publications
counts <- list()
for (pub in pubs) {
  if (is.null(pub$id)) next
  key <- normalise_title(if (is.null(pub$scholar_title)) pub$title else pub$scholar_title)
  match <- which(scholar_keys == key)
  if (length(match) >= 1) {
    counts[[pub$id]] <- as.integer(scholar_pubs$cites[match[1]])
    message(sprintf("%-25s %3d", pub$id, counts[[pub$id]]))
  } else {
    message(sprintf("%-25s not found on Google Scholar (add `scholar_title` if the title differs)", pub$id))
  }
}

writeLines(
  c(
    "# Citation counts shown in the \"Citations\" column, keyed by publication `id`.",
    "# Generated by `Rscript scripts/update_citations.R` (Google Scholar); it is",
    "# fine to edit by hand. The website build never contacts Google Scholar, so",
    "# builds are reproducible and do not fail when Scholar blocks requests.",
    yaml::as.yaml(list(
      source = paste0("Google Scholar (", scholar_id, ")"),
      updated = format(Sys.Date()),
      counts = counts
    ))
  ),
  citations_path
)
message("Updated ", citations_path)
